export const CITIES = Object.keys(RAW).sort((a, b) => a.localeCompare(b, 'tr'));

export const RAW_NEIGHBORS = Object.fromEntries(
  Object.entries(RAW).map(([city, list]) => [city, list.split(',')]),
);

const neighbors = new Map(CITIES.map((c) => [c, new Set()]));
for (const [city, list] of Object.entries(RAW_NEIGHBORS)) {
  for (const other of list) {
    neighbors.get(city).add(other);
    neighbors.get(other)?.add(city);
  }
}

export const areNeighbors = (a, b) => neighbors.get(a)?.has(b) ?? false;
